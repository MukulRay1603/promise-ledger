class StuckDocuments(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.store = storage.LocalStorage(Path(self.tmp.name))
        self.store.put_deal({"id": "d1", "name": "Deal"})
        old = (datetime.now(timezone.utc) - timedelta(hours=1)).isoformat()
        self.store.put_document("d1", {"id": "x1", "status": "reading", "updated_at": old, "started_at": old})

    def tearDown(self):
        self.tmp.cleanup()

    def test_a_stuck_document_is_queued_again_then_stopped(self):
        with mock.patch.object(deals, "submit") as submit, mock.patch.object(deals, "is_stale", return_value=True):
            for _ in range(healing.HEAL_MAX_RETRIES):
                self.assertEqual(healing.heal_stuck_documents(self.store)["requeued"], 1)
            last = healing.heal_stuck_documents(self.store)
        self.assertEqual(submit.call_count, healing.HEAL_MAX_RETRIES)
        self.assertEqual(last["stopped"], 1)
        doc = self.store.get_document("d1", "x1")
        self.assertEqual(doc["status"], "failed")
        self.assertIn("Press Retry", doc["error"])

    def test_one_failing_check_does_not_stop_the_others(self):
        with mock.patch.object(healing, "heal_search_index", side_effect=RuntimeError("boom")), \
                mock.patch.object(healing, "heal_county_data", return_value={"ok": True}), \
                mock.patch.object(deals, "submit"):
            checks = healing.run_once(self.store)
        self.assertFalse(checks["search_index"]["ok"])
        self.assertTrue(checks["storage"]["ok"])
        self.assertIn("answer_model", checks["model"])


class RealRecordBytes(unittest.TestCase):
    """A redeploy never drops a county record because the source now serves a regenerated file."""

    def setUp(self):
        import hashlib
        self.tmp = tempfile.TemporaryDirectory()
        self.folder = Path(self.tmp.name)
        self.data = b"%PDF-1.4 checked copy"
        self.sha = hashlib.sha256(self.data).hexdigest()
        self.entry = {"sha256": self.sha, "url": "https://example.invalid/x.pdf"}

    def tearDown(self):
        self.tmp.cleanup()

    def test_bundled_copy_first(self):
        (self.folder / "files").mkdir()
        (self.folder / "files" / f"{self.sha[:32]}.pdf").write_bytes(self.data)
        with mock.patch.object(deals, "record_bytes") as download:
            self.assertEqual(deals.real_record_bytes(self.entry, self.folder, mock.Mock(), {}), self.data)
        download.assert_not_called()

    def test_the_stored_copy_is_kept_when_the_source_changed(self):
        store = mock.Mock()
        store.get_blob.return_value = self.data
        with mock.patch.object(deals, "record_bytes", return_value=None) as download:
            got = deals.real_record_bytes(self.entry, self.folder, store, {self.sha: {"file_key": "k"}})
        self.assertEqual(got, self.data)
        download.assert_not_called()

    def test_a_file_with_another_hash_is_never_used(self):
        store = mock.Mock()
        store.get_blob.return_value = b"regenerated by the source"
        with mock.patch.object(deals, "record_bytes", return_value=None):
            self.assertIsNone(deals.real_record_bytes(self.entry, self.folder, store, {self.sha: {"file_key": "k"}}))


